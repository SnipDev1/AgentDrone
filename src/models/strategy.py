"""Pydantic models for bank decision recommendations and Act of Inspection report.

Defines schemas for the 5 bank strategies, risk classification,
and data required for generating the official Collateral Inspection Act (Приложение 1).
"""

from datetime import datetime, date, timezone
from typing import Any, List
from pydantic import BaseModel, Field, model_validator

from .enums import BankStrategy, RiskLevel, CollateralCondition
from .credit import CreditObject
from .inspection import InspectionResult


class StrategyRecommendation(BaseModel):
    """Target banking strategy recommendation generated by Decision Engine."""
    strategy: BankStrategy = Field(..., description="Одна из 5 целевых стратегий Банка")
    decision_code: str = Field(..., description="Уникальный код правила (напр. STRAT_TRANCHE_OK)")
    risk_level: RiskLevel = Field(default=RiskLevel.LOW, description="Уровень кредитного/залогового риска")
    confidence: float = Field(default=1.0, ge=0.0, le=1.0, description="Уверенность в решении (0..1)")
    is_automated: bool = Field(
        default=False,
        description="Возможность автоматической обработки (STP / безрисковый коридор)"
    )
    reasons: List[str] = Field(default_factory=list, description="Факторы и аргументы принятия решения")
    action_items: List[str] = Field(
        default_factory=list,
        description="Конкретные предписанные действия для инспектора и кредитора"
    )
    summary: str = Field(..., description="Экспертное резюме для АС «Калита»")
    created_at: datetime = Field(
        default_factory=lambda: datetime.now(timezone.utc),
        description="Время принятия решения"
    )


class ReportPhotoItem(BaseModel):
    """Photo entry included in the inspection report photo table."""
    file_path: str = Field(..., description="Путь к файлу изображения")
    caption: str = Field(..., description="Подпись (ракурс, фасад, дата съемки)")
    is_key_view: bool = Field(default=False, description="Флаг ключевого ракурса")


class ActReportData(BaseModel):
    """Complete dataset for rendering 'Акт проверки имущества (Приложение 1)'."""
    act_number: str = Field(..., description="Номер акта осмотра")
    act_date: date = Field(..., description="Дата составления акта")
    credit: CreditObject = Field(..., description="Параметры кредитного договора и заемщика")
    inspection: InspectionResult = Field(..., description="Результаты натурного осмотра с БПЛА")
    recommendation: StrategyRecommendation = Field(..., description="Решение и предписания Decision Engine")
    condition: CollateralCondition = Field(
        default=CollateralCondition.SATISFACTORY,
        description="Итоговое состояние обеспечения (Удовлетворительное / Неудовлетворительное)"
    )
    inspector_name: str = Field(
        default="Автоматизированный комплекс ИИ «AgentDrone»",
        description="ФИО инспектора / название системы мониторинга"
    )
    inspector_position: str = Field(
        default="Главный инспектор направления мониторинга залогов Сибирского банка",
        description="Должность инспектора"
    )
    branch_name: str = Field(
        default="Сибирский банк ПАО Сбербанк",
        description="Наименование филиала Банка"
    )
    photos: List[ReportPhotoItem] = Field(
        default_factory=list,
        description="Фототаблица подтверждающих снимков"
    )

    @model_validator(mode="before")
    @classmethod
    def _coerce_reloaded_models(cls, data: Any) -> Any:
        if not isinstance(data, dict):
            return data
        out = dict(data)
        for k, v in list(out.items()):
            if hasattr(v, "model_dump"):
                out[k] = v.model_dump()
            elif isinstance(v, list):
                out[k] = [item.model_dump() if hasattr(item, "model_dump") else item for item in v]
        return out
